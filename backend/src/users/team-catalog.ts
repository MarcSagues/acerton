export interface FavoriteTeam {
  name: string;
  primary: string;
  secondary: string;
}

export const FAVORITE_TEAMS: readonly FavoriteTeam[] = TEAMS.map(([name, primary, secondary]) => ({
  name,
  primary,
  secondary,
}));

export const FAVORITE_TEAM_NAMES: readonly string[] = FAVORITE_TEAMS.map((team) => team.name);

/** El equipo del catalogo con ese nombre, o null (sin equipo, o uno que ya no esta en el catalogo). */
export function findFavoriteTeam(name: string | null | undefined): FavoriteTeam | null {
  if (!name) return null;
  return FAVORITE_TEAMS.find((team) => team.name === name) ?? null;
}
