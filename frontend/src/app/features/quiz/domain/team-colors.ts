export interface TeamColors {
  primary: string;
  secondary: string;
}

export function teamColors(fullName: string): TeamColors | null {
  const colors = TEAM_COLORS.get(fullName.trim());
  return colors ? { primary: colors[0], secondary: colors[1] } : null;
}

/** Disco partido en diagonal con los dos colores del club. */
export function teamDiscBackground(colors: TeamColors): string {
  return `linear-gradient(135deg, ${colors.primary} 50%, ${colors.secondary} 50%)`;
}
